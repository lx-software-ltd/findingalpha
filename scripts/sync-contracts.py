#!/usr/bin/env python3
"""Copy contracts/*.json into the engine and the admin SPA.

`roadmap.json` stays out of the Lambda. An output whose parent folder
does not exist yet is skipped with a note, so this script runs before
those folders are created.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_LAMBDA = {"roadmap.json"}


def _contracts(root: Path) -> list[Path]:
    folder = root / "contracts"
    return sorted(path for path in folder.glob("*.json") if path.is_file())


def _typescript(payloads: list[tuple[str, object]]) -> str:
    lines = [
        "// Generated by scripts/sync-contracts.py. Do not edit.",
        "",
    ]
    for name, payload in payloads:
        ident = "".join(part.capitalize() for part in name.replace(".json", "").split("-"))
        const = ident[0].lower() + ident[1:] if ident else ident
        lines.append(f"export const {const} = {json.dumps(payload, indent=2)} as const;")
        lines.append("")
    return "\n".join(lines)


def sync(root: Path) -> list[str]:
    """Write generated files under root. Return notes for skipped outputs."""
    notes: list[str] = []
    files = _contracts(root)
    engine_dir = root / "backend" / "lambda" / "engine" / "contracts"
    if engine_dir.parent.exists():
        engine_dir.mkdir(parents=True, exist_ok=True)
        for path in files:
            if path.name in SKIP_LAMBDA:
                continue
            target = engine_dir / path.name
            target.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
    else:
        notes.append(f"skip {engine_dir}: parent folder does not exist")

    shared = root / "backend" / "infrastructure" / "lib" / "shared-contracts.ts"
    domains = root / "contracts" / "admin-domains.json"
    if shared.parent.exists() and domains.is_file():
        payload = json.loads(domains.read_text(encoding="utf-8"))
        shared.write_text(
            "\n".join(
                [
                    "// Generated by scripts/sync-contracts.py. Do not edit.",
                    f"export const storageKeyPrefix = {json.dumps(payload['storageKeyPrefix'])};",
                    f"export const cognitoDomainPrefix = {json.dumps(payload['cognitoDomainPrefix'])};",
                    "",
                ]
            ),
            encoding="utf-8",
        )
    elif not shared.parent.exists():
        notes.append(f"skip {shared}: parent folder does not exist")

    ts_path = root / "apps" / "admin_web" / "src" / "lib" / "contracts" / "generated.ts"
    if ts_path.parent.exists():
        payloads = []
        for path in files:
            payloads.append((path.name, json.loads(path.read_text(encoding="utf-8"))))
        ts_path.write_text(_typescript(payloads), encoding="utf-8")
    else:
        notes.append(f"skip {ts_path}: parent folder does not exist")
    return notes


def main() -> int:
    for note in sync(ROOT):
        print(note)
    print("contracts synced")
    return 0


if __name__ == "__main__":
    sys.exit(main())
